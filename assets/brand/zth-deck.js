'use strict';
/* From Zero to Hero presentation: language, slide navigation (buttons, keys, swipe, course map), per-language book
   diagrams loaded when their slide opens, and the copy-prompt button. Copy comes from window.ZTH_DECK
   (assets/products/zth/deck-copy.js, generated by scripts/zero_to_hero/deck.py). No dependencies. */
(()=>{
 const COPY=window.ZTH_DECK||{};const LANGS=['ar','en','ru'];
 const deck=document.querySelector('[data-zdeck]');
 const get=(obj,path)=>path.split('.').reduce((v,k)=>v==null?v:v[k],obj);
 /* The catalog page has covers but no deck: only the cover language swap runs there. */
 document.addEventListener('ali:language',e=>apply(e.detail.lang));
 const slides=deck?[...deck.querySelectorAll('[data-slide]')]:[];const total=slides.length;
 const reduced=matchMedia('(prefers-reduced-motion: reduce)');
 const svgCache={};let index=0;
 let lang=new URLSearchParams(location.search).get('lang');
 if(!LANGS.includes(lang)){try{lang=localStorage.getItem('ali-language')}catch(e){lang=null}}
 if(!LANGS.includes(lang))lang=document.documentElement.lang;
 if(!LANGS.includes(lang))lang='en';

 function diagrams(slide){
  slide.querySelectorAll('[data-diagram]').forEach(box=>{
   const key=box.dataset.diagram+'-'+lang;if(box.dataset.loaded===key)return;box.dataset.loaded=key;
   const put=svg=>{if(box.dataset.loaded!==key)return;box.innerHTML=svg;
    const title=box.querySelector('svg>title');const slot=box.closest('figure').querySelector('[data-fig-title]');if(title&&slot)slot.textContent=title.textContent};
   if(svgCache[key])return put(svgCache[key]);
   fetch('/assets/products/zth/diagrams/'+key+'.svg').then(r=>r.ok?r.text():'').then(svg=>{svgCache[key]=svg;put(svg)}).catch(()=>{box.dataset.loaded=''});
  });
 }
 function apply(next){
  lang=LANGS.includes(next)?next:'en';const c=COPY[lang]||{};
  document.querySelectorAll('[data-src-'+lang+']').forEach(el=>{el.src=el.getAttribute('data-src-'+lang)});
  if(!deck)return;
  deck.querySelectorAll('[data-t]').forEach(el=>{const v=get(c,el.dataset.t);if(typeof v==='string')el.textContent=v});
  deck.querySelectorAll('[data-t-label]').forEach(el=>{const v=get(c,el.dataset.tLabel);if(typeof v==='string')el.setAttribute('aria-label',v)});
  deck.querySelectorAll('[data-diagram]').forEach(box=>{if(box.dataset.loaded&&!box.dataset.loaded.endsWith('-'+lang)){box.dataset.loaded='';box.replaceChildren()}});
  diagrams(slides[index]);
 }
 function show(i,focus,dir){
  index=Math.max(0,Math.min(i,total-1));
  slides.forEach((s,n)=>{s.hidden=n!==index;s.classList.remove('entering')});
  const active=slides[index];
  if(!reduced.matches&&dir){active.style.setProperty('--dir',String(dir*(lang==='ar'?-1:1)));void active.offsetWidth;active.classList.add('entering')}
  deck.querySelector('[data-count]').textContent=String(index+1).padStart(2,'0')+' / '+String(total).padStart(2,'0');
  deck.querySelector('[data-progress]').style.width=((index+1)/total*100)+'%';
  deck.querySelector('[data-prev]').disabled=index===0;deck.querySelector('[data-next]').disabled=index===total-1;
  deck.querySelectorAll('[data-map] [data-goto]').forEach(b=>b.setAttribute('aria-current',String(Number(b.dataset.goto)===index+1)));
  diagrams(active);
  // warm the next slide's diagram so it is ready when the visitor moves on
  if(slides[index+1])setTimeout(()=>diagrams(slides[index+1]),400);
  if(focus){const h=active.querySelector('h3');h&&h.focus({preventScroll:true})}
 }
 if(!deck){apply(lang);return}
 deck.querySelector('[data-prev]').addEventListener('click',()=>show(index-1,false,-1));
 deck.querySelector('[data-next]').addEventListener('click',()=>show(index+1,false,1));
 deck.addEventListener('click',e=>{const g=e.target.closest('[data-goto]');if(g){const n=Number(g.dataset.goto)-1;show(n,true,n>index?1:-1)}});
 deck.addEventListener('keydown',e=>{
  if(e.target.closest('input,select,textarea'))return;
  if(e.key==='Home'||e.key==='End'){e.preventDefault();show(e.key==='Home'?0:total-1,true,0);return}
  if(e.key!=='ArrowRight'&&e.key!=='ArrowLeft')return;
  e.preventDefault();const forward=(e.key==='ArrowRight')!==(lang==='ar');show(index+(forward?1:-1),true,forward?1:-1);
 });
 const stage=deck.querySelector('[data-stage]');let x0=null,y0=null;
 stage.addEventListener('pointerdown',e=>{if(e.pointerType==='mouse'||e.target.closest('.zd-svg'))return;x0=e.clientX;y0=e.clientY});
 stage.addEventListener('pointerup',e=>{if(x0===null)return;const dx=e.clientX-x0,dy=e.clientY-y0;x0=null;if(Math.abs(dx)<50||Math.abs(dx)<Math.abs(dy)*1.4)return;const forward=(dx<0)!==(lang==='ar');show(index+(forward?1:-1),false,forward?1:-1)});
 stage.addEventListener('pointercancel',()=>{x0=null});
 /* Copy the sample prompt; fall back to selecting it where the clipboard is blocked. */
 const copyBtn=deck.querySelector('[data-copy]');
 if(copyBtn)copyBtn.addEventListener('click',async()=>{
  const src=deck.querySelector('[data-copy-source]');const label=copyBtn.querySelector('[data-copy-label]');const c=COPY[lang]||{};
  try{await navigator.clipboard.writeText(src.textContent);label.textContent=c.copied||'';setTimeout(()=>{label.textContent=c.copy||''},1800)}
  catch(e){const r=document.createRange();r.selectNodeContents(src);const s=getSelection();s.removeAllRanges();s.addRange(r)}
 });
 apply(lang);show(0);
})();
